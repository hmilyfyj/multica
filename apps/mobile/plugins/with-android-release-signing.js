/**
 * Injects the release signing config into the generated `android/app/build.gradle`.
 *
 * The native project is a prebuild artifact (gitignored, rewritten on every
 * `expo prebuild`), and `expo-build-properties` has no signingConfig support, so
 * the signing block can only come from a config plugin. Everything the plugin
 * writes is appended at the END of the file inside the two marker comments
 * below rather than spliced into the template's existing `signingConfigs { }` /
 * `buildTypes.release { }` blocks: Gradle's `android { }` extension can be
 * reopened and the last assignment wins, so an append depends on no template
 * text at all. An anchored splice would silently stop matching after an Expo
 * upgrade, and its failure mode — a "release" APK quietly signed with the debug
 * key — is exactly the kind nobody notices.
 *
 * Signing material stays OUTSIDE the repo, addressed through a standard Android
 * `keystore.properties` (see docs/android-distribution.md):
 *
 *   storeFile=/Users/…/.multica-android/multica-release.keystore
 *   storePassword=…
 *   keyAlias=multica-release
 *   keyPassword=…
 *
 * `MULTICA_ANDROID_KEYSTORE_PROPERTIES` points at a different properties file —
 * that is how a team that already owns a signing key (or CI, writing the file
 * from a secret) swaps the self-use key out. The resolved absolute path is baked
 * into the appended block so the key used at prebuild time is the key Gradle
 * signs with; the password itself never reaches a file inside android/.
 *
 * A missing properties file is NOT an error here. This plugin runs on every
 * prebuild, debug included (the variant is chosen later, by run:android or
 * Gradle), so throwing would break the ordinary `pnpm android:mobile:device`
 * flow for anyone without a key. Instead the appended block falls back to the
 * template's debug signing config — today's upstream behaviour — and the
 * prebuild logs a warning. Enforcement lives in scripts/android-release.sh,
 * which is the side that actually produces a distributable artifact.
 */
const fs = require("node:fs");
const os = require("node:os");
const path = require("node:path");

const { withAppBuildGradle } = require("expo/config-plugins");

const MARKER_START = "// >>> multica-release-signing (generated by plugins/with-android-release-signing.js)";
const MARKER_END = "// <<< multica-release-signing";

const DEFAULT_PROPERTIES_PATH = path.join(os.homedir(), ".multica-android", "keystore.properties");

/** Where scripts/android-keystore.sh writes its output by default; overridable. */
function resolvePropertiesPath() {
  const configured = process.env.MULTICA_ANDROID_KEYSTORE_PROPERTIES;
  return configured && configured.trim().length > 0 ? configured.trim() : DEFAULT_PROPERTIES_PATH;
}

/** A Groovy double-quoted string literal, for the path baked into the block. */
function groovyString(value) {
  return `"${value.replace(/\\/g, "\\\\").replace(/"/g, '\\"')}"`;
}

function signingBlock(propertiesPath) {
  return [
    MARKER_START,
    "// Regenerated on every `expo prebuild` — change plugins/with-android-release-signing.js,",
    "// never this block. The keystore and its passwords live outside the repository.",
    "def multicaReleaseKeystoreProperties = new Properties()",
    `def multicaReleaseKeystorePropertiesFile = new File(${groovyString(propertiesPath)})`,
    "def multicaHasReleaseKeystore = multicaReleaseKeystorePropertiesFile.exists()",
    "if (multicaHasReleaseKeystore) {",
    "    multicaReleaseKeystoreProperties.load(new FileInputStream(multicaReleaseKeystorePropertiesFile))",
    "}",
    "android {",
    "    signingConfigs {",
    "        release {",
    "            if (multicaHasReleaseKeystore) {",
    "                storeFile file(multicaReleaseKeystoreProperties['storeFile'])",
    "                storePassword multicaReleaseKeystoreProperties['storePassword']",
    "                keyAlias multicaReleaseKeystoreProperties['keyAlias']",
    "                keyPassword multicaReleaseKeystoreProperties['keyPassword']",
    "            }",
    "        }",
    "    }",
    "    buildTypes {",
    "        release {",
    "            // Without a keystore.properties this stays on the template's debug key, which",
    "            // keeps any build working; scripts/android-release.sh refuses to produce a",
    "            // distributable artifact in that state.",
    "            if (multicaHasReleaseKeystore) {",
    "                signingConfig signingConfigs.release",
    "            } else {",
    "                signingConfig signingConfigs.debug",
    "            }",
    "        }",
    "    }",
    "}",
    MARKER_END,
  ].join("\n");
}

/** Drop a block appended by an earlier run, so the markers appear exactly once. */
function stripPreviousBlock(contents) {
  const start = contents.indexOf(MARKER_START);
  if (start === -1) return contents;
  const end = contents.indexOf(MARKER_END, start);
  if (end === -1) return contents.slice(0, start);
  return contents.slice(0, start) + contents.slice(end + MARKER_END.length);
}

module.exports = function withAndroidReleaseSigning(config) {
  const propertiesPath = resolvePropertiesPath();

  if (!fs.existsSync(propertiesPath)) {
    console.log(
      `with-android-release-signing: no keystore properties at ${propertiesPath} — release builds will be ` +
        "signed with the debug key. Run `pnpm android:mobile:keystore` for a self-use key, or point " +
        "MULTICA_ANDROID_KEYSTORE_PROPERTIES at an existing keystore.properties.",
    );
  }

  return withAppBuildGradle(config, (gradleConfig) => {
    const stripped = stripPreviousBlock(gradleConfig.modResults.contents);
    gradleConfig.modResults.contents = `${stripped.replace(/\s*$/, "")}\n\n${signingBlock(propertiesPath)}\n`;
    return gradleConfig;
  });
};
